/**
 * Korean particle helpers based on Hangul batchim (final consonant).
 */
function getBatchimInfo(str) {
  const clean = String(str || '')
    .replace(/\([^)]*\)/g, '')
    .replace(/[\s"'.,?!~·\-]+$/g, '');
  if (!clean) return { has: false, isRieul: false };
  const ch = clean[clean.length - 1];
  const code = ch.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    const jong = (code - 0xac00) % 28;
    return { has: jong !== 0, isRieul: jong === 8 };
  }
  const digitMap = {
    '0': { has: true, isRieul: false },
    '1': { has: true, isRieul: true },
    '2': { has: false, isRieul: false },
    '3': { has: true, isRieul: false },
    '4': { has: false, isRieul: false },
    '5': { has: false, isRieul: false },
    '6': { has: true, isRieul: false },
    '7': { has: true, isRieul: true },
    '8': { has: true, isRieul: true },
    '9': { has: false, isRieul: false },
  };
  if (digitMap[ch]) return digitMap[ch];
  return { has: false, isRieul: false };
}

function eun(w) {
  return w + (getBatchimInfo(w).has ? '은' : '는');
}
function iga(w) {
  return w + (getBatchimInfo(w).has ? '이' : '가');
}
function eul(w) {
  return w + (getBatchimInfo(w).has ? '을' : '를');
}
function euro(w) {
  const b = getBatchimInfo(w);
  return w + (b.has && !b.isRieul ? '으로' : '로');
}
function wa(w) {
  return w + (getBatchimInfo(w).has ? '과' : '와');
}

